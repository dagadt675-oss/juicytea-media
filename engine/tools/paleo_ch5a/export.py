import json, numpy as np
from scipy.spatial import cKDTree
exec(open('classify.py').read().split("coast={}")[0])
def load(T): return json.load(open(P+'coast_%03d.json'%T))
mem=json.load(open('member2.json'))
ADD=mem.pop('_added_nonrigid',{})  # pieces on separate GPlates plates (southern cone, NE Africa/Horn): drawn with their continent
c0=load(0)
names=['africa','samerica','india','australia','antarctica']
trees={c:cKDTree(np.concatenate([V(c0[i]) for i in mem[c]])) for c in names}
trees2={c:cKDTree(np.concatenate([V(c0[i]) for i in ids])) for c,ids in ADD.items()}
excl=[]; ant=[]
for T in range(0,201):
    polys=load(T); ex=[]; an=[]
    for j,p in enumerate(polys):
        pv=V(p); samp=pv[np.linspace(0,len(pv)-1,min(len(pv),8)).astype(int)]
        for c in names:
            q=samp@R(c,T)   # inverse rotation: R^T applied to row vectors -> samp @ R
            d,_=trees[c].query(q)
            if np.median(d)<np.radians(0.06):
                (an if c=='antarctica' else ex).append(j); break
            if c in trees2:  # not rigid with the tracked rotation: looser match so they leave no sand ghost
                d2,_=trees2[c].query(q)
                if np.median(d2)<np.radians(1.5): ex.append(j); break
    excl.append(ex); ant.append(an)
    if T%20==0: print(T,len(polys),len(ex),len(an))
rings={c:[[[round(a,3),round(b,3)] for a,b in c0[i]] for i in mem[c]] for c in ['africa','samerica','india','australia']}
out='// generated by work_ch5a/export.py: present-day coastline rings of the tracked plates (from paleo/coast_000.json)\n'
out+='// and, per Ma 0..200, indices of coast_TTT polygons that belong to the tracked plates (EXCL) or to Antarctica (ANT).\n'
out+='export const RINGS='+json.dumps(rings,separators=(',',':'))+';\n'
out+='export const EXCL='+json.dumps(excl,separators=(',',':'))+';\n'
out+='export const ANT='+json.dumps(ant,separators=(',',':'))+';\n'
